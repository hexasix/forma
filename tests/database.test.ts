import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
const A = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
const B = 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb';
let db: PGlite, taskId: string, memberId: string, labelId: string;
async function asUser(id: string) {
  await db.exec(
    `reset role; set role authenticated; select set_config('request.jwt.claim.sub', '${id}', false);`,
  );
}
async function scalar(sql: string) {
  return (await db.query<Record<string, unknown>>(sql)).rows[0];
}
beforeAll(async () => {
  db = new PGlite();
  await db.exec(
    `create role anon; create role authenticated; create schema auth; create table auth.users(id uuid primary key); insert into auth.users values ('${A}'), ('${B}'); create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$; grant usage on schema auth, public to authenticated, anon; grant execute on function auth.uid() to authenticated, anon;`,
  );
  await db.exec(
    readFileSync(new URL('../supabase/migrations/001_initial.sql', import.meta.url), 'utf8'),
  );
  await asUser(A);
  memberId = (await scalar("insert into public.members(name) values ('Alex') returning id"))!
    .id as string;
  labelId = (await scalar("insert into public.labels(name) values ('Design') returning id"))!
    .id as string;
  taskId = (await scalar(
    `select public.save_task(null,'Private task','Context','todo','high',null,array['${memberId}'::uuid],array['${labelId}'::uuid]) as id`,
  ))!.id as string;
  await db.exec(
    `insert into public.comments(task_id,body) values ('${taskId}','Private initial comment')`,
  );
});
afterAll(async () => {
  await db?.close();
});
describe('actual PostgreSQL schema, RLS, RPC and triggers', () => {
  it('lets owner read tasks and activity generated by triggers', async () => {
    await asUser(A);
    expect((await db.query('select * from public.tasks')).rows).toHaveLength(1);
    expect(
      (await db.query('select * from public.activity_log')).rows.length,
    ).toBeGreaterThanOrEqual(2);
  });
  it('hides every owner-owned table from a different guest', async () => {
    await asUser(B);
    for (const table of [
      'tasks',
      'members',
      'labels',
      'task_assignees',
      'task_labels',
      'comments',
      'activity_log',
    ])
      expect((await db.query(`select * from public.${table}`)).rows).toHaveLength(0);
  });
  it('blocks reading, editing and deleting another guest’s task', async () => {
    await asUser(B);
    expect(
      (await db.query(`update public.tasks set title='Hijacked' where id='${taskId}' returning id`))
        .rows,
    ).toHaveLength(0);
    expect(
      (await db.query(`delete from public.tasks where id='${taskId}' returning id`)).rows,
    ).toHaveLength(0);
    await expect(
      db.query(`select public.save_task('${taskId}','Hijacked','','done','low',null,'{}','{}')`),
    ).rejects.toThrow();
  });
  it('blocks spoofing the owner on insert', async () => {
    await asUser(B);
    await expect(
      db.query(`insert into public.tasks(user_id,title) values ('${A}','Spoofed')`),
    ).rejects.toThrow();
  });
  it('blocks transferring ownership to another guest', async () => {
    await asUser(A);
    await expect(
      db.query(`update public.tasks set user_id='${B}' where id='${taskId}'`),
    ).rejects.toThrow();
  });
  it('blocks cross-owner comments and relationships with composite foreign keys', async () => {
    await asUser(B);
    await expect(
      db.query(`insert into public.comments(task_id,body) values ('${taskId}','Intrusion')`),
    ).rejects.toThrow();
    const other = (await scalar(
      "insert into public.tasks(title) values ('Other task') returning id",
    ))!.id;
    await expect(
      db.query(
        `insert into public.task_assignees(task_id,member_id) values ('${other}','${memberId}')`,
      ),
    ).rejects.toThrow();
    await expect(
      db.query(`insert into public.task_labels(task_id,label_id) values ('${other}','${labelId}')`),
    ).rejects.toThrow();
  });
  it('rolls back a complete save when an invalid relationship is supplied', async () => {
    await asUser(B);
    const before = (await scalar('select count(*)::int as count from public.tasks'))!.count;
    await expect(
      db.query(
        `select public.save_task(null,'Rollback me','','todo','normal',null,array['${memberId}'::uuid],'{}')`,
      ),
    ).rejects.toThrow();
    expect((await scalar('select count(*)::int as count from public.tasks'))!.count).toBe(before);
  });
  it('does not let clients fabricate or remove activity records', async () => {
    await asUser(A);
    await expect(
      db.query(
        `insert into public.activity_log(user_id,task_id,message) values ('${A}','${taskId}','Fake')`,
      ),
    ).rejects.toThrow();
    await expect(db.query('delete from public.activity_log')).rejects.toThrow();
  });
  it('records status changes and supports comments', async () => {
    await asUser(A);
    await db.exec(
      `update public.tasks set status='in_progress' where id='${taskId}'; insert into public.comments(task_id,body) values ('${taskId}','An owner comment');`,
    );
    expect(
      (
        await db.query(
          "select * from public.activity_log where message='Moved from To do → In progress'",
        )
      ).rows,
    ).toHaveLength(1);
    expect((await db.query('select * from public.comments')).rows).toHaveLength(2);
  });
  it('cascades member and task deletion without recreating dangling activity', async () => {
    await asUser(A);
    await db.exec(`delete from public.members where id='${memberId}';`);
    expect((await db.query('select * from public.task_assignees')).rows).toHaveLength(0);
    const replacement = (await scalar(
      "insert into public.members(name) values ('Sam') returning id",
    ))!.id;
    await db.exec(
      `insert into public.task_assignees(task_id,member_id) values ('${taskId}','${replacement}'); delete from public.tasks where id='${taskId}'`,
    );
    for (const table of ['tasks', 'comments', 'activity_log', 'task_assignees', 'task_labels'])
      expect((await db.query(`select * from public.${table}`)).rows).toHaveLength(0);
  });
  it('grants unauthenticated visitors no table access', async () => {
    await db.exec('reset role; set role anon;');
    await expect(db.query('select * from public.tasks')).rejects.toThrow();
  });
});
